#!/usr/bin/env node
// Refreshes the generated sections of the READMEs from results/*.json.
//
//   node benchmarks/report.mjs
//
// Each README carries a `<!-- benchmarks:start -->` … `<!-- benchmarks:end -->`
// block (and the overviews a `<!-- languages:start -->` … `<!-- languages:end -->`
// block); everything between the markers is regenerated. The site renders the
// same results at build time (site/vite.config.js), so nothing else to update.

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { speedMarkdown, conformanceMarkdown, languagesMarkdown } from './render.mjs'
import { LANGUAGES } from './languages.mjs'

const root = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url))
const results = {}
for (const l of LANGUAGES) {
  const p = root(`benchmarks/results/${l.id}.json`)
  if (existsSync(p)) results[l.id] = JSON.parse(readFileSync(p, 'utf8'))
}

const section = (res, heading) => [
  `${heading} Speed`,
  '',
  speedMarkdown(res),
  '',
  `${heading} Conformance`,
  '',
  conformanceMarkdown(res),
].join('\n')

const NOTE = '<!-- Generated by benchmarks/report.mjs from benchmarks/results/. Do not edit by hand. -->'

const replace = (file, name, body) => {
  const path = root(file)
  if (!existsSync(path)) return console.error(`skip ${file}: missing`)
  const text = readFileSync(path, 'utf8')
  const START = `<!-- ${name}:start -->`
  const END = `<!-- ${name}:end -->`
  const i = text.indexOf(START)
  const j = text.indexOf(END)
  if (i === -1 || j === -1) return
  const next = `${text.slice(0, i + START.length)}\n${NOTE}\n\n${body}\n\n${text.slice(j)}`
  if (next !== text) {
    writeFileSync(path, next)
    console.log(`updated ${file} (${name})`)
  }
}

for (const l of LANGUAGES) {
  if (results[l.id]) replace(l.readme, 'benchmarks', section(results[l.id], '###'))
}
replace(
  'benchmarks/README.md',
  'benchmarks',
  LANGUAGES.filter((l) => results[l.id]).map((l) => `## ${l.name}\n\n${section(results[l.id], '###')}`).join('\n\n'),
)
replace('benchmarks/README.md', 'languages', languagesMarkdown(LANGUAGES, results, '../'))
replace('README.md', 'languages', languagesMarkdown(LANGUAGES, results))
